// Helper functions
export function getArticleById(id: string): Article | undefined {
  return articles?.find(article => article?.id === id);
}

export function getLatestArticles(count: number = 6): Article[] {
  return articles?.slice(0, count) ?? [];
}

export function getRelatedArticles(currentId: string, count: number = 3): Article[] {
  const current = getArticleById(currentId);
  if (!current) return [];
  
  // Find articles with overlapping tags
  const related = articles
    ?.filter(article => article?.id !== currentId)
    ?.map(article => {
      const commonTags = article?.tags?.filter(tag => 
        current?.tags?.includes(tag)
      )?.length ?? 0;
      return { article, commonTags };
    })
    ?.filter(item => (item?.commonTags ?? 0) > 0)
    ?.sort((a, b) => (b?.commonTags ?? 0) - (a?.commonTags ?? 0))
    ?.slice(0, count)
    ?.map(item => item?.article)
    ?? [];
  
  // If not enough related articles, fill with latest
  if (related?.length < count) {
    const additional = articles
      ?.filter(article => 
        article?.id !== currentId && 
        !related?.some(r => r?.id === article?.id)
      )
      ?.slice(0, count - (related?.length ?? 0))
      ?? [];
    return [...related, ...additional];
  }
  
  return related;
}

export function getAllTags(): string[] {
  const tagSet = new Set<string>();
  articles?.forEach(article => {
    article?.tags?.forEach(tag => tagSet.add(tag));
  });
  return Array.from(tagSet);
}

export function filterArticles({
  searchQuery,
  selectedTags,
  sortBy = 'date'
}: {
  searchQuery?: string;
  selectedTags?: string[];
  sortBy?: 'date' | 'views' | 'citations';
}): Article[] {
  let filtered = [...(articles ?? [])];
  
  // Filter by search query
  if (searchQuery?.trim()) {
    const query = searchQuery?.toLowerCase();
    filtered = filtered?.filter(article =>
      article?.title?.toLowerCase()?.includes(query) ||
      article?.summary?.toLowerCase()?.includes(query) ||
      article?.authors?.some(author => author?.toLowerCase()?.includes(query))
    ) ?? [];
  }
  
  // Filter by tags
  if (selectedTags?.length && selectedTags?.length > 0) {
    filtered = filtered?.filter(article =>
      selectedTags?.some(tag => article?.tags?.includes(tag))
    ) ?? [];
  }
  
  // Sort
  filtered?.sort((a, b) => {
    if (sortBy === 'date') {
      return new Date(b?.date ?? 0)?.getTime() - new Date(a?.date ?? 0)?.getTime();
    } else if (sortBy === 'views') {
      return (b?.views ?? 0) - (a?.views ?? 0);
    } else if (sortBy === 'citations') {
      return (b?.citations ?? 0) - (a?.citations ?? 0);
    }
    return 0;
  });
  
  return filtered;
}